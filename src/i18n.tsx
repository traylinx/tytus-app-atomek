const maps: Record<string, LocaleMap> = { en, es };
const normalizeLocale = (locale: string | undefined): string => (locale || 'en').toLowerCase().split('-')[0] || 'en';
const interpolate = (text: string, vars?: Vars): string => vars ? text.replace(/\{(\w+)\}/g, (_, key) => String(vars[key] ?? `{${key}}`)) : text;

const I18nContext = createContext<{ locale: string; t: T }>({ locale: 'en', t: (key) => en[key] ?? key });

export function AtomekI18nProvider({ host, children }: { host: HostClient; children: ReactNode }) {
  const [locale, setLocale] = useState(() => normalizeLocale(host.i18n?.locale));
  useEffect(() => host.i18n?.onLocaleChange((next) => setLocale(normalizeLocale(next))), [host]);
  const value = useMemo(() => ({
    locale,
    t: (key: string, vars?: Vars) => {
      const hostText = host.i18n?.t(key, vars);
      if (hostText && hostText !== key) return hostText;
      return interpolate(maps[locale]?.[key] ?? maps.en[key] ?? key, vars);
    },
  }), [host, locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useAtomekT(): T {
  return useContext(I18nContext).t;
}

export function useAtomekLocale(): string {
  return useContext(I18nContext).locale;
}
